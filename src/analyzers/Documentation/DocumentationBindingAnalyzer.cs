using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Diagnostics;
using Specht.Analysis.Bindings;
using Specht.Analysis.Policy;

namespace Specht.Analysis.Documentation;

/// <summary>Checks explicit XML relationships on documentable CSharp declarations.</summary>
#pragma warning disable RS1004 // 0201-F2 decision 0003 selects CSharp declarations.
[DiagnosticAnalyzer(LanguageNames.CSharp)]
public sealed class DocumentationBindingAnalyzer : DiagnosticAnalyzer
{
    public override ImmutableArray<DiagnosticDescriptor> SupportedDiagnostics => new DocumentationDiagnostics().Descriptors;

    public override void Initialize(AnalysisContext context)
    {
        context.EnableConcurrentExecution();
        context.ConfigureGeneratedCodeAnalysis(GeneratedCodeAnalysisFlags.Analyze | GeneratedCodeAnalysisFlags.ReportDiagnostics);
#pragma warning disable RSA1007 // Roslyn registration receives callbacks rather than invoking a delegate.
        context.RegisterCompilationStartAction(start =>
        {
            var snapshot = new AnalysisInputAdapter().Read(start.Options.AdditionalFiles, start.Options.AnalyzerConfigOptionsProvider,
                start.Compilation.SyntaxTrees, start.CancellationToken);
            if (!snapshot.Available)
            {
                return;
            }

            var resolver = new BindingResolver(snapshot.Catalog!, snapshot.Policy!.Bindings);
            var recognized = new DocumentationTestMethods().Read(start.Options, start.CancellationToken);
            start.RegisterSymbolAction(symbol => Analyze(symbol, snapshot.Policy, resolver, recognized),
                SymbolKind.NamedType, SymbolKind.Method, SymbolKind.Property, SymbolKind.Field, SymbolKind.Event);
        });
#pragma warning restore RSA1007
    }

    private static void Analyze(SymbolAnalysisContext context, AnalysisPolicy policy, BindingResolver resolver, HashSet<string> recognized)
    {
        if (context.Symbol.IsImplicitlyDeclared || context.Symbol is IMethodSymbol { AssociatedSymbol: not null }
            || context.Symbol.DeclaringSyntaxReferences.Length == 0)
        {
            return;
        }

        var options = context.Options.AnalyzerConfigOptionsProvider;
        if (!options.GlobalOptions.TryGetValue("build_property.SpechtProjectPath", out var project)
            || !options.GlobalOptions.TryGetValue("build_property.TargetFramework", out var framework))
        {
            return;
        }

        var symbolId = context.Symbol.GetDocumentationCommentId() ?? context.Symbol.MetadataName;
        var reference = context.Symbol.DeclaringSyntaxReferences[0];
        var path = reference.SyntaxTree.FilePath.Replace('\\', '/');
        if (options.GetOptions(reference.SyntaxTree).TryGetValue("specht_relative_path", out var relative))
        {
            path = relative;
        }

        try
        {
            path = new AnalysisPaths().Normalize(path);
        }
        catch (ArgumentException)
        {
            return;
        }

        var syntax = reference.GetSyntax(context.CancellationToken);
        var generated = path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
            || reference.SyntaxTree.GetRoot(context.CancellationToken).GetLeadingTrivia().ToFullString().Contains("<auto-generated");
        var selection = policy.Select(new AnalysisDeclaration(project, framework, path, Kind(syntax), symbolId, generated, recognized.Contains(symbolId)));
        if (!selection.ValidateExplicit)
        {
            return;
        }

        var result = new DocumentationBindingReader().Read(context.Symbol, resolver, recognized.Contains(symbolId), context.CancellationToken);
        var descriptors = new DocumentationDiagnostics().Descriptors;
        foreach (var finding in result.Findings)
        {
            context.ReportDiagnostic(Diagnostic.Create(descriptors.Single(descriptor => descriptor.Id == finding.Id),
                finding.Location, finding.Reference));
        }

        foreach (var role in selection.RequiredRoles.Where(role => !result.Relationships.Any(binding => binding.Role == role)))
        {
            context.ReportDiagnostic(Diagnostic.Create(descriptors.Single(static descriptor => descriptor.Id == "SPCT0007"),
                context.Symbol.Locations.FirstOrDefault() ?? Location.None, symbolId + " requires " + role));
        }
    }

    private static string Kind(SyntaxNode syntax) => syntax switch
    {
        ClassDeclarationSyntax => "class",
        RecordDeclarationSyntax => "record",
        StructDeclarationSyntax => "struct",
        InterfaceDeclarationSyntax => "interface",
        EnumDeclarationSyntax => "enum",
        DelegateDeclarationSyntax => "delegate",
        ConstructorDeclarationSyntax => "constructor",
        PropertyDeclarationSyntax => "property",
        IndexerDeclarationSyntax => "indexer",
        EventDeclarationSyntax => "event",
        VariableDeclaratorSyntax variable => variable.Parent?.Parent is EventFieldDeclarationSyntax ? "event" : "field",
        _ => "method",
    };
}
