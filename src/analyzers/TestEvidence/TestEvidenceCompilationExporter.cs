using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.IO;
using System.Linq;
using System.Security.Cryptography;
using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Diagnostics;
using Microsoft.CodeAnalysis.Text;
using Specht.Analysis.Bindings;
using Specht.Analysis.Documentation;
using Specht.Analysis.Policy;

namespace Specht.Analysis.TestEvidence;

[Generator]
public sealed class TestEvidenceCompilationExporter : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var inputs = context.CompilationProvider
            .Combine(context.AdditionalTextsProvider.Collect())
            .Combine(context.AnalyzerConfigOptionsProvider);
        context.RegisterSourceOutput(inputs, static (production, input) => Export(production,
            input.Left.Left, input.Left.Right, input.Right));
    }

    private static void Export(SourceProductionContext context, Compilation compilation,
        IReadOnlyList<AdditionalText> additionalFiles, AnalyzerConfigOptionsProvider options)
    {
        if (!options.GlobalOptions.TryGetValue("build_property.SpechtRoot", out var root)
            || !options.GlobalOptions.TryGetValue("build_property.SpechtProjectPath", out var projectPath)
            || !options.GlobalOptions.TryGetValue("build_property.TargetFramework", out var framework)
            || !options.GlobalOptions.TryGetValue("build_property.Configuration", out var configuration))
        {
            return;
        }

        root = Path.GetFullPath(root);
        projectPath = NormalizeRelative(root, Path.GetFullPath(Path.Combine(root, projectPath)));
        if (projectPath is null)
        {
            return;
        }

        var snapshot = new AnalysisInputAdapter().Read(additionalFiles.ToImmutableArray(), options,
            compilation.SyntaxTrees, context.CancellationToken);
        if (!snapshot.Available)
        {
            return;
        }

        var resolver = new BindingResolver(snapshot.Catalog!, snapshot.Policy!.Bindings);
        var methodExporter = new TestEvidenceMethodExporter();
        var bindingExporter = new TestEvidenceBindingExporter();
        var methods = new List<TestEvidenceMethod>();
        var bindings = new List<TestEvidenceBinding>();

        foreach (var type in GetNamespaceTypes(compilation.Assembly.GlobalNamespace))
        {
            foreach (var method in type.GetMembers().OfType<IMethodSymbol>().Where(static method =>
                         method.MethodKind == MethodKind.Ordinary && !method.IsImplicitlyDeclared))
            {
                context.CancellationToken.ThrowIfCancellationRequested();
                var syntax = method.DeclaringSyntaxReferences.FirstOrDefault();
                var relativePath = syntax is null ? null : RelativeSourcePath(root, syntax.SyntaxTree, options);
                methods.Add(methodExporter.Export(method, relativePath));
                if (relativePath is null)
                {
                    continue;
                }

                var analysis = new DocumentationBindingReader().Read(method, resolver, recognizedTest: true,
                    context.CancellationToken);
                bindings.AddRange(bindingExporter.Export(analysis, relativePath));
            }
        }

        var inputs = ReadInputs(root, additionalFiles, compilation.SyntaxTrees, options, context.CancellationToken);
        var fingerprint = new TestEvidenceFingerprint();
        var sourceFingerprint = fingerprint.ComputeDigests(inputs.Where(static input =>
            input.Kind is "source" or "generated-source"));
        var policyFingerprint = fingerprint.ComputeDigests(inputs.Where(static input =>
            input.Kind is "manifest" or "schema" or "record"));
        var configurationFingerprint = Hash(string.Join("\n", compilation.Options.ToString(),
            string.Join("\n", compilation.References.Select(static reference => reference.Display ?? string.Empty)
                .OrderBy(static name => name, StringComparer.Ordinal))));
        var payload = new CompilationEvidence(projectPath, framework, configuration, null,
            configurationFingerprint, sourceFingerprint, policyFingerprint, methods, bindings, inputs);
        var json = JsonSerializer.Serialize(payload, new JsonSerializerOptions { PropertyNamingPolicy = JsonNamingPolicy.CamelCase });
        var source = "// Generated by Specht.CodeAnalysis.\nnamespace Specht.Generated { "
            + "internal static class TestEvidenceCompilationExport { internal const string Json = "
            + Microsoft.CodeAnalysis.CSharp.SymbolDisplay.FormatLiteral(json, quote: true) + "; } }";
        context.AddSource("Specht.TestEvidence.CompilationExport.g.cs", source);
    }

    private static List<TestEvidenceInput> ReadInputs(string root, IReadOnlyList<AdditionalText> files,
        IEnumerable<SyntaxTree> syntaxTrees, AnalyzerConfigOptionsProvider options,
        System.Threading.CancellationToken cancellationToken)
    {
        var inputs = new List<TestEvidenceInput>();
        foreach (var file in files)
        {
            var metadata = options.GetOptions(file);
            if (!metadata.TryGetValue("build_metadata.AdditionalFiles.SpechtInputKind", out var kind)
                || !metadata.TryGetValue("build_metadata.AdditionalFiles.SpechtRelativePath", out var path)
                || file.GetText(cancellationToken) is not { } text)
            {
                continue;
            }

            var normalized = NormalizeRelative(root, Path.Combine(root, path));
            var mappedKind = kind == "configuration" ? "manifest"
                : kind == "schema" || kind.StartsWith("schema:", StringComparison.Ordinal) ? "schema"
                : kind is "feature" or "scenario" or "adr" ? "record" : null;
            if (normalized is not null && mappedKind is not null)
            {
                inputs.Add(new TestEvidenceInput(normalized, HashText(text), mappedKind));
            }
        }

        foreach (var tree in syntaxTrees)
        {
            var path = RelativeSourcePath(root, tree, options);
            if (path is null || tree.GetText(cancellationToken) is not { } text)
            {
                continue;
            }

            var generated = path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
                || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase)
                || tree.GetRoot(cancellationToken).GetLeadingTrivia().ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
            inputs.Add(new TestEvidenceInput(path, HashText(text), generated ? "generated-source" : "source"));
        }

        return inputs.Distinct().OrderBy(static input => input.Path, StringComparer.Ordinal)
            .ThenBy(static input => input.Kind, StringComparer.Ordinal).ToList();
    }

    private static string? RelativeSourcePath(string root, SyntaxTree tree, AnalyzerConfigOptionsProvider options)
    {
        if (options.GetOptions(tree).TryGetValue("specht_relative_path", out var path))
        {
            return NormalizeRelative(root, Path.Combine(root, path));
        }

        return NormalizeRelative(root, tree.FilePath);
    }

    private static string? NormalizeRelative(string root, string path)
    {
        if (string.IsNullOrWhiteSpace(path))
        {
            return null;
        }

        var fullPath = Path.GetFullPath(path);
        var relative = Uri.UnescapeDataString(new Uri(EnsureTrailingSeparator(root))
            .MakeRelativeUri(new Uri(fullPath)).ToString()).Replace('\\', '/');
        return relative == ".." || relative.StartsWith("../", StringComparison.Ordinal) || Path.IsPathRooted(relative)
            ? null
            : relative;
    }

    private static string EnsureTrailingSeparator(string path) => path.EndsWith(Path.DirectorySeparatorChar.ToString(), StringComparison.Ordinal)
        ? path
        : path + Path.DirectorySeparatorChar;

    private static string HashText(SourceText text)
    {
        var encoding = text.Encoding ?? new UTF8Encoding(encoderShouldEmitUTF8Identifier: false);
        using var sha = SHA256.Create();
        return Hex(sha.ComputeHash(encoding.GetBytes(text.ToString())));
    }

    private static string Hash(string value)
    {
        using var sha = SHA256.Create();
        return Hex(sha.ComputeHash(Encoding.UTF8.GetBytes(value)));
    }

    private static string Hex(byte[] bytes) => string.Concat(bytes.Select(static value => value.ToString("x2")));

    private static IEnumerable<INamedTypeSymbol> GetNamespaceTypes(INamespaceSymbol root)
    {
        foreach (var member in root.GetMembers())
        {
            if (member is INamespaceSymbol child)
            {
                foreach (var type in GetNamespaceTypes(child))
                {
                    yield return type;
                }
            }
            else if (member is INamedTypeSymbol type)
            {
                yield return type;
                foreach (var nested in GetNestedTypes(type))
                {
                    yield return nested;
                }
            }
        }
    }

    private static IEnumerable<INamedTypeSymbol> GetNestedTypes(INamedTypeSymbol type)
    {
        foreach (var nested in type.GetTypeMembers())
        {
            yield return nested;
            foreach (var child in GetNestedTypes(nested))
            {
                yield return child;
            }
        }
    }

    private sealed record CompilationEvidence(string ProjectPath, string TargetFramework, string ConfigurationName,
        string? AssemblyPath, string ConfigurationFingerprint, string SourceFingerprint, string PolicyFingerprint,
        IReadOnlyList<TestEvidenceMethod> Methods, IReadOnlyList<TestEvidenceBinding> Bindings,
        IReadOnlyList<TestEvidenceInput> Inputs);
}
