using System;
using System.Linq;
using Microsoft.CodeAnalysis;

namespace Specht.Analysis.TestEvidence;

public sealed class TestEvidenceMethodExporter
{
    public TestEvidenceMethod Export(IMethodSymbol method, string? relativePath)
    {
        var symbolId = method.GetDocumentationCommentId()
            ?? throw new InvalidOperationException("A method without a documentation-comment ID cannot be exported.");
        var source = method.Locations.FirstOrDefault(static location => location.IsInSource);
        TestEvidenceLocation? location = null;
        if (source?.SourceTree is { } tree && IsSource(tree) && IsRepositoryRelative(relativePath))
        {
            var position = source.GetLineSpan().StartLinePosition;
            location = new TestEvidenceLocation(relativePath!, position.Line + 1, position.Character + 1);
        }

        return new TestEvidenceMethod(symbolId, method.ContainingType.MetadataName, method.MetadataName,
            method.Arity, method.Parameters.Select(static parameter =>
                parameter.Type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat.WithMiscellaneousOptions(
                    SymbolDisplayFormat.FullyQualifiedFormat.MiscellaneousOptions & ~SymbolDisplayMiscellaneousOptions.UseSpecialTypes))).ToArray(), location);
    }

    private static bool IsSource(SyntaxTree tree)
    {
        var path = tree.FilePath.Replace('\\', '/');
        if (path.EndsWith(".g.cs", StringComparison.OrdinalIgnoreCase)
            || path.EndsWith(".generated.cs", StringComparison.OrdinalIgnoreCase))
        {
            return false;
        }

        return !tree.GetRoot().GetLeadingTrivia().ToFullString().Contains("<auto-generated", StringComparison.OrdinalIgnoreCase);
    }

    private static bool IsRepositoryRelative(string? path)
    {
        if (path is not { Length: > 0 } relativePath)
        {
            return false;
        }

        return relativePath[0] != '/' && !relativePath.Contains('\\')
            && !(relativePath.Length > 1 && char.IsLetter(relativePath[0]) && relativePath[1] == ':')
            && !relativePath.Split('/').Any(static component => component is "" or "." or "..");
    }
}
